def render_table_file(pkg: str, s: SchemaInfo, custom_go: str) -> str:
    public = go_public_name(s.table_key)
    private = go_private_name(public)

    current_struct = render_go_struct(f"{public}CurrentSchema", s.current_fields)
    history_struct = render_go_struct(f"{public}HistorySchema", s.history_fields)

    save_fields = list(s.search_fields) + list(s.data_fields)
    save_struct = render_go_struct(
        f"{public}SaveSchema",
        save_fields,
        use_save_types=True,
    )

    # В этом файле мы всегда используем time.Time в сигнатуре Save(...)
    import_block = 'import (\n\t"time"\n)\n\n'

    params: List[str] = []
    entity_map_lines: List[str] = []
    for ef in s.entity_fields:
        t = go_type_for_save(ef.ft)
        pname = ef.name
        if pname in ("type", "var", "func", "map", "range"):
            pname = pname + "Val"
        params.append(f"{pname} {t}")
        entity_map_lines.append(f"\"{ef.name}\": {pname},")

    save_method = ""
    if params:
        jj = "\n\t\t".join(entity_map_lines)
        save_method = f"""
func (t *{private}) Save(client *Client, {", ".join(params)}, data *{public}SaveSchema, now time.Time) (SaveResponse, error) {{
\tentity := map[string]any{{
\t\t{jj}
\t}}
\treturn client.Save(t.name, entity, data, now)
}}
""".rstrip()
    else:
        save_method = f"""
func (t *{private}) Save(client *Client, data *{public}SaveSchema, now time.Time) (SaveResponse, error) {{
\tentity := map[string]any{{}}
\treturn client.Save(t.name, entity, data, now)
}}
""".rstrip()

    get_by_entity = ""
    if params:
        jj = "\n\t\t".join(entity_map_lines)
        get_by_entity = f"""
func (t *{private}) GetByEntity(client *Client, {", ".join(params)}) (*{public}CurrentSchema, error) {{
\tentity := map[string]any{{
\t\t{jj}
\t}}
\tvar resp {public}CurrentSchema
\tfound, err := client.Get(t.name, entity, &resp)
\tif err != nil {{
\t\treturn nil, err
\t}}
\tif !found {{
\t\treturn nil, nil
\t}}
\treturn &resp, nil
}}
""".rstrip()

    query_resp = f"""type {public}QueryResponse struct {{
\tResults []{public}CurrentSchema `json:"results"`
\tCount   int32                 `json:"count"`
\tTotal   int32                 `json:"total"`
}}"""

    hist_resp = f"""type {public}HistoryResponse struct {{
\tResults []{public}HistorySchema `json:"results"`
\tCount   int32                  `json:"count"`
\tTotal   int32                  `json:"total"`
}}"""

    group_resp = f"""type {public}GroupResponse struct {{
\tResults []map[string]any `json:"results"`
\tCount   int32            `json:"count"`
\tTotal   int32            `json:"total"`
}}"""

    methods = f"""
var {public} = &{private}{{name: "{s.table_key}"}}

func (t *{private}) Name() string {{
\treturn t.name
}}

{save_method}

{get_by_entity}

func (t *{private}) Query(client *Client, filters any, q *Q) (resp {public}QueryResponse, err error) {{
\terr = client.Query(t.name, filters, q, &resp)
\treturn
}}

func (t *{private}) History(client *Client, filters any, q *Q) (resp {public}HistoryResponse, err error) {{
\terr = client.History(t.name, filters, q, &resp)
\treturn
}}

func (t *{private}) Group(client *Client, filters any, groupBy []string, aggs map[string]any, q *Q) (resp {public}GroupResponse, err error) {{
\terr = client.Group(t.name, filters, groupBy, aggs, q, &resp)
\treturn
}}
""".rstrip()

    custom_block = ""
    custom_go = (custom_go or "").strip()
    if custom_go:
        custom_block = "\n\n" + custom_go.rstrip() + "\n"

    return _HEADER + f"""package {pkg}

{import_block}type {private} struct {{
\tname string
}}

{current_struct}

{history_struct}

{save_struct}

{query_resp}

{hist_resp}

{group_resp}

{methods}{custom_block}
"""


def main() -> None:
    if load_dotenv:
        load_dotenv()

    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    ap.add_argument("--pkg", default="dsm")
    ap.add_argument("--pythonpath", default="")
    ap.add_argument("--tables", default=os.getenv("TABLES_CONFIG_PATH", ""))
    args = ap.parse_args()

    if not args.tables:
        raise SystemExit("tables.yaml path is required: --tables or TABLES_CONFIG_PATH")

    if args.pythonpath:
        for p in args.pythonpath.split(","):
            p = p.strip()
            if p:
                sys.path.insert(0, p)

    # default out = ./gen/{parent_dir}/{pkg}
    if not args.out:
        tables_path = os.path.normpath(args.tables)
        parent_dir = os.path.basename(os.path.dirname(tables_path))
        args.out = os.path.join(".", "gen", parent_dir, args.pkg)

    out_dir = Path(args.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    table_refs = parse_tables_yaml(args.tables)
    if not table_refs:
        raise SystemExit("No tables found in tables.yaml (expected: tables.<key>.schema)")

    schemas: List[SchemaInfo] = []
    for table_key, ref in table_refs:
        schema_obj = import_by_ref(ref)
        schemas.append(extract_schema_info(table_key, schema_obj))

    write_file(out_dir / "dsm.go", render_dsm_go(args.pkg))

    for s in sorted(schemas, key=lambda x: x.table_key):
        custom_go = CUSTOM_FUNCTIONS.get(s.table_key, "")
        file_name = safe_file_name(s.table_key) + ".go"
        write_file(out_dir / file_name, render_table_file(args.pkg, s, custom_go))

    print(f"Generated: {out_dir}")
    print(f"Tables: {len(schemas)}")
    for s in schemas:
        print(f" - {s.table_key} (schema_name={s.schema_name})")


if __name__ == "__main__":
    main()
